    PreProc = { fg = c.heather },
    Macro = { fg = c.heather },
    Type = { fg = c.fg1 },
    Special = { fg = c.purple_grey },
    SpecialChar = { fg = c.taupe },
    Tag = { fg = c.heather },
    Delimiter = { fg = c.purple_grey },
